// 실제 JLPT 기출 지문은 저작권이 있어 쓸 수 없다.
// 아래 지문·문항은 공식 출제 «형식»(短文 / 中文 / 情報検索)만 따라
// N3 어휘·문법 범위 안에서 직접 만든 것이다.

enum ReadingKind: String, CaseIterable, Identifiable {
    case short  // 短文 — 150~200자, 1문항
    case medium // 中文 — 300~400자, 3문항
    case info   // 情報検索 — 안내문·광고에서 필요한 정보 찾기

    var id: String { rawValue }

    var name: String {
        switch self {
        case .short:  return "短文"
        case .medium: return "中文"
        case .info:   return "情報検索"
        }
    }

    var korean: String {
        switch self {
        case .short:  return "단문 · 짧은 글 1문항"
        case .medium: return "중문 · 긴 글 3문항"
        case .info:   return "정보 검색 · 안내문에서 찾기"
        }
    }

    var icon: String {
        switch self {
        case .short:  return "doc.text"
        case .medium: return "doc.richtext"
        case .info:   return "list.bullet.rectangle"
        }
    }

    /// 실제 시험에서 이 유형에 주는 시간(분) — 페이스 감각을 잡기 위한 목표
    var minutesPerPassage: Int {
        switch self {
        case .short:  return 3
        case .medium: return 8
        case .info:   return 5
        }
    }
}

struct ReadingVocab: Identifiable {
    let word: String
    let reading: String
    let meaning: String
    var id: String { word }
}

struct ReadingQuestion: Identifiable {
    let id: String
    let prompt: String
    let choices: [String]
    let answerIndex: Int
    /// 왜 그 답인지 — 한국어
    let explanation: String
}

struct ReadingPassage: Identifiable {
    let id: String
    let kind: ReadingKind
    /// 목록에 보여줄 한국어 제목
    let title: String
    let body: String
    /// 한국어 번역 — 지문 아래에서 켰다 껐다 한다.
    /// 먼저 일본어로 읽고, 확인할 때만 열어 보는 용도라 기본은 접혀 있다.
    let translation: String
    let questions: [ReadingQuestion]
    let vocab: [ReadingVocab]
}

